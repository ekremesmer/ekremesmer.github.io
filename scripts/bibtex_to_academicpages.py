#!/usr/bin/env python3
"""Convert SciX/ADS BibTeX into Academic Pages publication Markdown.

Standard library only. Does not modify the input bibliography and will not
replace unrelated Markdown files in _publications.
"""
from __future__ import annotations

import argparse
import json
import re
import sys
import unicodedata
from datetime import date
from pathlib import Path

SIGNATURE = '<!-- Generated by bibtex_to_academicpages.py; edit bibliography/publications.bib instead. -->'
MONTHS = {m: i for i, m in enumerate(['jan','feb','mar','apr','may','jun','jul','aug','sep','oct','nov','dec'], 1)}
JOURNALS = {'\\aj': 'The Astronomical Journal', '\\aap': 'Astronomy & Astrophysics',
            '\\mnras': 'Monthly Notices of the Royal Astronomical Society',
            '\\na': 'New Astronomy', '\\actaa': 'Acta Astronomica',
            '\\apss': 'Astrophysics and Space Science'}
ACCENTS = {'"':'\u0308', "'":'\u0301', '`':'\u0300', '^':'\u0302', '~':'\u0303',
           'v':'\u030c', 'c':'\u0327', 'u':'\u0306', '.':'\u0307', '=':'\u0304',
           'H':'\u030b', 'k':'\u0328', 'r':'\u030a'}
REPL = {'\\textcommabelow': '\u0326', '\\i': 'ı', '\\j':'ȷ',
        '\\ss':'ß', '\\ae':'æ', '\\AE':'Æ', '\\oe':'œ', '\\OE':'Œ',
        '\\aa':'å', '\\AA':'Å', '\\o':'ø', '\\O':'Ø', '\\l':'ł', '\\L':'Ł'}

def latex_plain(s: str) -> str:
    s = s.replace('~', ' ')
    for cmd, value in JOURNALS.items():
        s = re.sub(re.escape(cmd) + r'(?=\s|\}|$)', lambda _: value, s)
    # BibTeX accent forms: {\\c{S}}, \\c{S}, \\c S, \\.I, \\"O.
    for _ in range(4):
        s = re.sub(r'\\(["\'`^~vcu.=Hkr])\s*\{([A-Za-zı])\}',
                   lambda m: m[2] + ACCENTS[m[1]], s)
        s = re.sub(r'\\(["\'`^~vcu.=Hkr])\s*([A-Za-zı])',
                   lambda m: m[2] + ACCENTS[m[1]], s)
    s = re.sub(r'([A-Za-z])\s*\{\\textcommabelow\}', lambda m: ('ş' if m[1] == 's' else 'Ş' if m[1] == 'S' else m[1] + '\u0326'), s)
    s = re.sub(r'\\textcommabelow\s*([A-Za-z])', lambda m: ('ş' if m[1] == 's' else 'Ş' if m[1] == 'S' else m[1] + '\u0326'), s)
    for cmd, value in sorted(REPL.items(), key=lambda kv: -len(kv[0])):
        s = re.sub(re.escape(cmd) + r'(?![A-Za-z])', lambda _: value, s)
    s = s.replace('{', '').replace('}', '').replace('\\&', '&').replace('\\#', '#')
    s = re.sub(r'\\([{}%_$])', r'\1', s)
    s = s.replace('\\', '')
    return unicodedata.normalize('NFC', re.sub(r'\s+', ' ', s).strip())

def parse_braced(text: str, start: int) -> tuple[str, int]:
    assert text[start] == '{'
    depth = 1
    i = start + 1
    while i < len(text) and depth:
        if text[i] == '{' and (i == 0 or text[i - 1] != '\\'):
            depth += 1
        elif text[i] == '}' and (i == 0 or text[i - 1] != '\\'):
            depth -= 1
        i += 1
    if depth: raise ValueError('Unclosed braced value')
    return text[start+1:i-1], i

def parse_entries(raw: str) -> list[dict[str,str]]:
    entries = []
    pattern = re.compile(r'@([A-Za-z]+)\s*\{\s*([^,\s]+)\s*,')
    pos = 0
    while match := pattern.search(raw, pos):
        kind, key = match[1].lower(), match[2]
        i = match.end(); fields: dict[str, str] = {'_type':kind, '_key':key}
        while i < len(raw):
            while i < len(raw) and (raw[i].isspace() or raw[i] == ','): i += 1
            if i == len(raw): raise ValueError(f'Unclosed BibTeX entry {key}')
            if raw[i] == '}':
                i += 1
                break
            fm = re.match(r'([\w-]+)\s*=\s*', raw[i:])
            if fm is None: raise ValueError(f'Invalid field near {key}: {raw[i:i+60]!r}')
            field = fm[1].lower(); i += fm.end()
            if raw[i] == '{': value, i = parse_braced(raw, i)
            elif raw[i] == '"':
                j = i+1
                while j < len(raw) and (raw[j] != '"' or raw[j-1] == '\\'): j += 1
                value, i = raw[i+1:j], j+1
            else:
                j = i
                while j < len(raw) and raw[j] not in ',}\n': j+=1
                value, i = raw[i:j].strip(), j
            fields[field] = value.strip()
        entries.append(fields); pos = i
    return entries

def authors_field(raw: str) -> str:
    authors = re.split(r'\s+and\s+', raw.strip())
    out = []
    for author in authors:
        if author.strip().lower() == 'et al.':
            out.append('et al.'); continue
        author = latex_plain(author)
        if ',' in author:
            surname, given = author.split(',', 1)
            names = [n for n in given.strip().split() if n]
            initials = ' '.join(n if (len(n) <= 3 and '.' in n) else n[0] + '.' for n in names)
            out.append(f'{surname.strip()}, {initials}'.strip())
        else:
            out.append(author)
    return '; '.join(out)

def compact_authors(full_authors: str) -> tuple[str, bool]:
    """Readable, author-position-aware credit; flag truncated unverified positions."""
    names = [x.strip() for x in full_authors.split(';') if x.strip()]
    known = [x for x in names if x.lower() not in ('et al.', 'others')]
    if not known:
        raise ValueError('No identifiable authors in BibTeX record')
    # Match different first/middle initial variants from the bibliography.
    def is_esmer(s: str) -> bool:
        return bool(re.match(r'^Esmer\s*,', s, flags=re.IGNORECASE))
    indices = [i for i, name in enumerate(known) if is_esmer(name)]
    shortened = len(known) != len(names)
    if indices:
        pos = indices[0]
        if pos == 0:
            return 'Esmer, E. M.; et al.' if len(known)>1 or shortened else 'Esmer, E. M.', False
        if pos == 1:
            return f'{known[0]}; Esmer, E. M.; et al.' if len(known)>2 or shortened else f'{known[0]}; Esmer, E. M.', False
        suffix = '; et al.' if shortened or pos < len(known)-1 else ''
        return f'{known[0]}; …; Esmer, E. M.{suffix}', False
    # ADS exports can truncate the author list before Esmer appears.
    # User has confirmed membership via their CV/ORCID export, but not exact order.
    return f'{known[0]}; …; Esmer, E. M.; et al.', True

def bib_date(rec: dict[str,str]) -> str:
    year = int(rec['year'])
    month_str = rec.get('month', 'jan').strip().strip('{}').lower()[:3]
    month = MONTHS.get(month_str, 1)
    day_value = rec.get('day', '1').strip()
    day = int(day_value) if day_value.isdigit() else 1
    return date(year, month, day).isoformat()

def slugify(key: str) -> str:
    return re.sub(r'[^a-z0-9]+', '-', key.lower()).strip('-')

def as_yaml_string(value: str) -> str:
    return json.dumps(value, ensure_ascii=False)

def render(rec: dict[str,str]) -> str:
    title = latex_plain(rec['title'])
    journal = latex_plain(rec.get('journal', rec.get('booktitle', rec.get('series', ''))))
    ads = rec.get('adsurl','')
    doi = rec.get('doi','').removeprefix('https://doi.org/')
    arxiv = rec.get('eprint', '') if rec.get('archiveprefix','').lower() == 'arxiv' else ''
    authors = authors_field(rec.get('author',''))
    display_authors, _ = compact_authors(authors)
    slug = slugify(rec['_key'])
    date_value = bib_date(rec)
    metadata = {'title':title,'collection':'publications',
                'category':'conferences' if rec['_type']=='inproceedings' else 'manuscripts',
                'permalink':f'/publication/{slug}/', 'date':date_value,
                'year':int(rec['year']), 'authors':authors, 'display_authors':display_authors, 'venue':journal,
                'volume':latex_plain(rec.get('volume','')),
                'pages':latex_plain(rec.get('pages',rec.get('eid',''))),
                'doi':doi,'arxiv':arxiv,'ads':ads}
    lines = ['---']
    for key,value in metadata.items():
        if value != '': lines.append(f'{key}: {value if isinstance(value,int) else as_yaml_string(value)}')
    lines += ['---','','',SIGNATURE,'',
              f'**{authors}** ({rec["year"]}).',
              f'*{journal}*'+(f', {metadata["volume"]}' if metadata['volume'] else '')+
              (f', {metadata["pages"]}' if metadata['pages'] else '')+'.','']
    links = []
    if doi: links.append(f'[DOI](https://doi.org/{doi})')
    if arxiv: links.append(f'[arXiv](https://arxiv.org/abs/{arxiv})')
    if ads: links.append(f'[ADS/SciX]({ads})')
    if links: lines += [' · '.join(links),'']
    return '\n'.join(lines)

def main() -> int:
    p = argparse.ArgumentParser()
    p.add_argument('--input', default='bibliography/publications.bib')
    p.add_argument('--output', default='_publications')
    p.add_argument('--expected-count', type=int, default=35)
    p.add_argument('--write', action='store_true', help='Write files; otherwise validate only')
    args = p.parse_args()
    src = Path(args.input); dest = Path(args.output)
    if not src.is_file(): p.error(f'Bibliography not found: {src}')
    records = parse_entries(src.read_text(encoding='utf-8-sig'))
    if len(records) != args.expected_count:
        p.error(f'Expected {args.expected_count} records, found {len(records)}; no files written')
    keys = [r['_key'] for r in records]
    if len(set(keys)) != len(keys): p.error('Duplicate BibTeX citation keys; no files written')
    filenames = [slugify(key)+'.md' for key in keys]
    if len(set(filenames)) != len(filenames): p.error('Filename collisions; no files written')
    for r in records:
        for field in ('title','author','year'):
            if not r.get(field): p.error(f'{r["_key"]} missing {field}')
        bib_date(r)
    uncertain = [r['_key'] for r in records if compact_authors(authors_field(r.get('author', '')))[1]]
    if uncertain:
        print('NOTICE: Author lists truncated before Esmer appears in these records; displaying first author, …, Esmer, et al.:')
        for key in uncertain: print(f'  - {key}')
        print('Verify authorship position from the publisher or full-author export before publishing.')
    if not args.write:
        print(f'Validated {len(records)} BibTeX records; no files written.')
        print('Record types:', ', '.join(f'{kind}={sum(r["_type"]==kind for r in records)}' for kind in sorted(set(r['_type'] for r in records))))
        print('Run with --write to generate Markdown files.')
        return 0
    dest.mkdir(exist_ok=True, parents=True)
    for name in filenames:
        path = dest / name
        if path.exists() and SIGNATURE not in path.read_text(encoding='utf-8'):
            p.error(f'Will not overwrite manually edited file: {path}')
    for name,record in zip(filenames,records):
        (dest/name).write_text(render(record), encoding='utf-8')
    print(f'Generated {len(records)} Markdown files in {dest}/')
    print('Check the local /publications/ page and your Git diff before committing.')
    return 0

if __name__ == '__main__':
    sys.exit(main())
