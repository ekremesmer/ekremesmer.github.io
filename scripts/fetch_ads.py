#!/usr/bin/env python3
"""Fetch my publications from SciX/ADS and write bibliography/publications.bib.

Standard library only. Needs an ADS API token in the ADS_TOKEN environment variable.

What it does
  1. Searches ADS for every record linked to my ORCID, keeping only
     journal articles and conference proceedings (no abstracts, no preprints).
  2. Drops anything listed as `exclude` in bibliography/overrides.txt.
  3. Exports the rest as BibTeX with *all* authors.
  4. Appends bibliography/manual.bib (papers ADS does not have, or that you
     want to control by hand). If a key exists in both, the manual one wins.
  5. Writes bibliography/publications.bib, which the converter script reads.

Usage
  ADS_TOKEN=... python scripts/fetch_ads.py            # fetch and write
  ADS_TOKEN=... python scripts/fetch_ads.py --dry-run  # show what would change
"""
from __future__ import annotations

import argparse
import json
import os
import re
import sys
import urllib.parse
import urllib.request
from pathlib import Path

ORCID = '0000-0002-6191-459X'
API = 'https://api.adsabs.harvard.edu/v1'
# Record types to keep. ADS uses e.g. 'abstract' for meeting abstracts and
# 'eprint' for arXiv-only preprints; those are left out on purpose.
DOCTYPES = ['article', 'inproceedings', 'inbook']

HEADER = ('% GENERATED by scripts/fetch_ads.py from SciX/ADS (ORCID {orcid}).\n'
          '% Do not edit by hand: changes are overwritten on the next run.\n'
          '% Put hand-made entries in bibliography/manual.bib and\n'
          '% exclusions/categories/venue fixes in bibliography/overrides.txt.\n\n')


def ads_request(path: str, token: str, payload: dict | None = None, params: dict | None = None) -> dict:
    url = f'{API}{path}'
    if params:
        url += '?' + urllib.parse.urlencode(params)
    data = json.dumps(payload).encode() if payload is not None else None
    req = urllib.request.Request(url, data=data, method='POST' if data else 'GET', headers={
        'Authorization': f'Bearer {token}', 'Content-Type': 'application/json'})
    with urllib.request.urlopen(req, timeout=60) as resp:
        return json.loads(resp.read().decode('utf-8'))


def search_bibcodes(token: str) -> list[dict]:
    query = f'orcid:"{ORCID}" doctype:(' + ' OR '.join(DOCTYPES) + ')'
    result = ads_request('/search/query', token, params={
        'q': query, 'fl': 'bibcode,doctype,title,year', 'rows': 2000, 'sort': 'date desc'})
    return result['response']['docs']


def export_bibtex(bibcodes: list[str], token: str) -> str:
    if not bibcodes:
        return ''
    result = ads_request('/export/bibtex', token, payload={
        'bibcode': bibcodes, 'maxauthor': 0, 'authorcutoff': 10000, 'sort': 'date desc'})
    return result['export']


def read_overrides(path: Path) -> dict[str, set[str]]:
    excludes: set[str] = set()
    if path.is_file():
        for line in path.read_text(encoding='utf-8').splitlines():
            line = line.split('#', 1)[0].strip()
            parts = line.split()
            if len(parts) >= 2 and parts[0].lower() == 'exclude':
                excludes.add(parts[1])
    return {'exclude': excludes}


def bib_keys(text: str) -> list[str]:
    return re.findall(r'@[A-Za-z]+\s*\{\s*([^,\s]+)\s*,', text)


def main() -> int:
    p = argparse.ArgumentParser()
    p.add_argument('--output', default='bibliography/publications.bib')
    p.add_argument('--manual', default='bibliography/manual.bib')
    p.add_argument('--overrides', default='bibliography/overrides.txt')
    p.add_argument('--dry-run', action='store_true')
    args = p.parse_args()

    token = os.environ.get('ADS_TOKEN', '').strip()
    if not token:
        p.error('Set the ADS_TOKEN environment variable (your SciX/ADS API token).')

    excludes = read_overrides(Path(args.overrides))['exclude']
    manual_text = Path(args.manual).read_text(encoding='utf-8') if Path(args.manual).is_file() else ''
    manual_keys = set(bib_keys(manual_text))

    docs = search_bibcodes(token)
    print(f'ADS returned {len(docs)} records for ORCID {ORCID} (types: {", ".join(DOCTYPES)}).')
    keep = []
    for d in docs:
        bc = d['bibcode']
        if bc in excludes:
            print(f'  excluded (overrides.txt): {bc}')
        elif bc in manual_keys:
            print(f'  using manual.bib instead: {bc}')
        else:
            keep.append(bc)

    ads_text = export_bibtex(keep, token)
    new_text = HEADER.format(orcid=ORCID) + ads_text.strip() + '\n'
    if manual_text.strip():
        new_text += '\n% ---- entries from bibliography/manual.bib ----\n\n' + manual_text.strip() + '\n'

    out = Path(args.output)
    old_keys = set(bib_keys(out.read_text(encoding='utf-8'))) if out.is_file() else set()
    new_keys = set(bib_keys(new_text))
    added, removed = sorted(new_keys - old_keys), sorted(old_keys - new_keys)
    print(f'Total entries: {len(new_keys)}  (ADS {len(keep)} + manual {len(manual_keys)})')
    for k in added: print(f'  + {k}')
    for k in removed: print(f'  - {k}')

    if args.dry_run:
        print('Dry run: nothing written.')
        return 0
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(new_text, encoding='utf-8')
    print(f'Wrote {out}')
    return 0


if __name__ == '__main__':
    sys.exit(main())
